const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  updatesStatus: () => ipcRenderer.invoke('updates:status'),
  updatesReady: () => ipcRenderer.invoke('updates:ready'),
  updatesCheck: () => ipcRenderer.invoke('updates:check'),
  updatesInstall: () => ipcRenderer.invoke('updates:install'),
  onUpdate: callback => { const handler=(_,state)=>callback(state);ipcRenderer.on('updates:state',handler);return ()=>ipcRenderer.removeListener('updates:state',handler); },
  load: () => ipcRenderer.invoke('state:load'),
  action: action => ipcRenderer.invoke('state:action', action),
  chat: (method,data) => ipcRenderer.invoke('chat:request',method,data),
  replace: state => ipcRenderer.invoke('state:replace', state),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  resumeSession: () => ipcRenderer.invoke('auth:resume'),
  register: credentials => ipcRenderer.invoke('auth:register', credentials),
  login: credentials => ipcRenderer.invoke('auth:login', credentials),
  resetPassword: credentials => ipcRenderer.invoke('auth:reset',credentials),
  copyText: text => ipcRenderer.invoke('text:copy',text),
  passwordResetCode: playerId => ipcRenderer.invoke('auth:reset-code',playerId),
  logout: () => ipcRenderer.invoke('auth:logout'),
  tutorialDone: () => ipcRenderer.invoke('auth:tutorial'),
  choosePicture: () => ipcRenderer.invoke('profile:picture'),
  chooseBanner: () => ipcRenderer.invoke('profile:banner'),
  networkInfo: () => ipcRenderer.invoke('network:info'),
  configureServer: url => ipcRenderer.invoke('network:configure',url),
  invitation: () => ipcRenderer.invoke('network:invite'),
  voicePlan: () => ipcRenderer.invoke('voice:plan'),
  captureSources: () => ipcRenderer.invoke('capture:sources'),
  selectCapture: (id,audio) => ipcRenderer.invoke('capture:select',id,audio),
  cancelCapture: () => ipcRenderer.invoke('capture:cancel'),
  voicePresence: () => ipcRenderer.invoke('voice:presence'),
  voiceDisconnect: () => ipcRenderer.invoke('voice:disconnect'),
  moveVoice: value => ipcRenderer.invoke('voice:move',value),
  visitVoice: squadId => ipcRenderer.invoke('voice:visit',squadId),
  pttStart: keys => ipcRenderer.invoke('voice:ptt-start',keys),
  pttStop: () => ipcRenderer.invoke('voice:ptt-stop'),
  voiceActivity: (speaking,channel) => ipcRenderer.send('voice:activity',{speaking,channel}),
  voiceStatus: value => ipcRenderer.send('voice:status',value),
  onNetwork: callback => { const handler=(_,event)=>callback(event);ipcRenderer.on('network:event',handler);return ()=>ipcRenderer.removeListener('network:event',handler); },
  onPtt: callback => { const handler=(_,held)=>callback(held);ipcRenderer.on('voice:keys',handler);return ()=>ipcRenderer.removeListener('voice:keys',handler); },
  export: () => ipcRenderer.invoke('state:export'),
  import: () => ipcRenderer.invoke('state:import'),
  minimize: () => ipcRenderer.send('window:minimize'),
  maximize: () => ipcRenderer.send('window:maximize'),
  close: () => ipcRenderer.send('window:close')
});
